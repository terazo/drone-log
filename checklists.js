// テキストを { sections: [{ title, items: [] }] } に変換する
export function parseChecklist(text) {
  const sections = [];
  let cur = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith('#')) {
      cur = { title: line.replace(/^#+\s*/, ''), items: [] };
      sections.push(cur);
    } else {
      if (!cur) { cur = { title: '', items: [] }; sections.push(cur); }
      cur.items.push(line);
    }
  }
  return sections;
}
